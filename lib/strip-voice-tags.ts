// 只用于「给用户看的语音文字」（语音条转文字气泡、通话字幕）。
// 语音合成走各自的 speechText、不经此函数，所以副语言/控制标记在声音里仍然保留，发音才自然。
//
// 洗掉的都是本来喂给 TTS 引擎、不该出现在字幕里的东西：
//   <#0.5#>            —— 停顿/时长控制标记
//   (chuckle)/(breath)/(轻笑)/（叹气）—— 括号里的副语言、语气、动作提示（半角+全角）
//   【叹气】           —— 方括号里的副语言/动作提示
//   *动作*             —— 星号包起来的动作描写
// 各条都带长度上限，避免把正常台词里的括注、书名号、强调号一并误删。
export function stripVoiceTagsForDisplay(s: string): string {
    return (s || "")
        .replace(/<#[^#]*#>/g, "")
        .replace(/[（(][^（()）\n]{0,30}[)）]/g, "")
        .replace(/【[^【】\n]{0,20}】/g, "")
        .replace(/\*[^*\n]{0,40}\*/g, "")
        .replace(/[ \t]{2,}/g, " ")
        .trim();
}
